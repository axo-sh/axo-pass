import * as browser from 'webextension-polyfill';

import type {Submission} from '@/lib/submit';

// Logins captured for saving, one per tab, kept in `storage.session`. The
// browser holds it in memory and never writes it to disk, and content scripts
// cannot read it. Chromium can stop the service worker before the user answers
// the save offer, so captures are not kept in memory. A capture is deleted
// after `CAPTURE_TTL_MS`, on tab close, and after a save or dismissal.
// Captured passwords are never logged and are sent only to the host.

/** Time a capture is kept. */
export const CAPTURE_TTL_MS = 5 * 60 * 1000;

/** Login captured from a submit or a generated password fill. */
export interface Capture extends Submission {
  id: string;
  tabId: number;
  frameId: number;
  frameUrl: string;
  topUrl: string;
  /** Whether the password was generated by Axo Pass. */
  generated: boolean;
  /** Capture time in milliseconds since the epoch. */
  createdAt: number;
}

const PREFIX = 'capture:';

const key = (tabId: number): string => {
  return `${PREFIX}${tabId}`;
};

/** Tab of a capture alarm, or `null` for another alarm. */
export const tabOfAlarm = (name: string): number | null => {
  if (!name.startsWith(PREFIX)) {
    return null;
  }
  const tabId = Number(name.slice(PREFIX.length));
  return Number.isInteger(tabId) ? tabId : null;
};

/**
 * Keep a capture for its tab, replacing any earlier one, and set an alarm for
 * its expiry. A capture of the same password in the same frame keeps the
 * earlier username if it has none, and stays marked as generated.
 */
export const storeCapture = async (capture: Capture): Promise<Capture> => {
  const earlier = await captureForTab(capture.tabId, capture.createdAt);
  let stored = capture;
  if (earlier && earlier.password === capture.password && earlier.frameUrl === capture.frameUrl) {
    stored = {
      ...capture,
      username: capture.username ?? earlier.username,
      generated: capture.generated || earlier.generated,
    };
  }
  await browser.storage.session.set({[key(capture.tabId)]: stored});
  await browser.alarms.create(key(capture.tabId), {when: capture.createdAt + CAPTURE_TTL_MS});
  return stored;
};

/** Capture of a tab, or `null`. An expired capture is deleted. */
export const captureForTab = async (tabId: number, now = Date.now()): Promise<Capture | null> => {
  const stored = (await browser.storage.session.get(key(tabId)))[key(tabId)] as Capture | undefined;
  if (!stored) {
    return null;
  }
  if (now - stored.createdAt >= CAPTURE_TTL_MS) {
    await clearCapture(tabId);
    return null;
  }
  return stored;
};

export const clearCapture = async (tabId: number): Promise<void> => {
  await browser.storage.session.remove(key(tabId));
  await browser.alarms.clear(key(tabId));
};
